const iso = (value: string) => new Date(value).toISOString();

const article = (
  id: string,
  slug: string,
  title: string,
  excerpt: string,
  date: string,
  tags: string[],
  body: string,
): ContentRecord => ({
  id,
  type: "article",
  slug,
  title,
  excerpt,
  body,
  tags,
  lang: "zh-CN",
  status: "published",
  featured: false,
  sortOrder: 0,
  publishedAt: iso(date),
  createdAt: iso(date),
  updatedAt: iso(date),
  seo: { keywords: tags },
});

